describe("§4.5 — promotion is one-way and additive", () => {
  const entry: TimelineEntry = {
    id: "j1", journeyId: "j", type: "journal", date: "2026-01-01T09:00:00Z",
    title: "A week in", detail: "Slower than I expected.", isAutoGenerated: false,
  };

  it("no entry means composing", () => {
    assert.equal(journalStateOf(undefined, []), "composing");
  });

  it("an entry with no body means composing", () => {
    assert.equal(journalStateOf({ ...entry, detail: "   " }, []), "composing");
  });

  it("an entry with no milestone pointing at it is reading", () => {
    assert.equal(journalStateOf(entry, [{ fromJournalEntryId: "other" }]), "reading");
  });

  it("THE ENTRY SURVIVES PROMOTION — it is not consumed", () => {
    // Promotion adds a milestone; it does not move or delete what was written.
    // `promoted` therefore describes an entry that still exists.
    assert.equal(journalStateOf(entry, [{ fromJournalEntryId: "j1" }]), "promoted");
  });
});

