describe("N6 — the report has no entitlement input at all", () => {
  it("deriveReport's signature cannot express a gate", () => {
    // Not a behavioural assertion but a structural one, and it is the strongest
    // form N6 can take in a pure function: there is no premium parameter, so
    // there is no way to write the gate even by mistake. An audit found the
    // report gated or sold in ten places; two had been photographed into
    // passing baselines.
    assert.equal(deriveReport.length, 2);
  });

  it("depth degrades on data alone", () => {
    assert.equal(deriveReport([], undefined).depth, "empty");
    assert.equal(deriveReport([checkIn("2026-01-01T09:00:00Z", 5)], undefined).depth, "sparse");
  });
});

