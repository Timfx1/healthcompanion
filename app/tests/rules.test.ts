import type { TimelineEntry } from "../src/types/recovery.ts";

const DAY = 86_400_000;

/** A check-in on a given ISO date, optionally with a pain score. */
function checkIn(date: string, pain?: number): TimelineEntry {
  return {
    id: date + (pain ?? "x"),
    journeyId: "j",
    type: "checkin",
    date,
    title: "Same",
    isAutoGenerated: false,
    data: pain === undefined ? { quick: "same" } : { quick: "same", pain },
  };
}

