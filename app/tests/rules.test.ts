describe("Day N", () => {
  it("the first day of a recovery is Day 1, not Day 0", () => {
    const start = "2026-01-01T00:00:00Z";
    assert.equal(dayNumber(start, Date.parse("2026-01-01T23:59:00Z")), 1);
    assert.equal(dayNumber(start, Date.parse("2026-01-02T00:00:00Z")), 2);
  });

  it("never goes below 1, even with a start date in the future", () => {
    assert.equal(dayNumber("2030-01-01T00:00:00Z", Date.parse("2026-01-01T00:00:00Z")), 1);
  });

  it("a malformed start date degrades to Day 1 rather than NaN", () => {
    assert.equal(dayNumber("not a date"), 1);
  });
});

