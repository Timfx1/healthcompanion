describe("the constraint that makes all of the above possible", () => {
  it("NOTHING IN rules/ IMPORTS REACT OR REACT NATIVE", () => {
    // The entire value of this suite rests on this one property. Every rule
    // here previously lived inside a component, and that is precisely why none
    // of them could be tested: the file imported `react-native` on line one.
    //
    // A rules module that quietly grows a `useState` is a rules module that has
    // stopped being testable and has taken these tests down with it — silently,
    // because the failure would look like an import error in a suite nobody
    // runs rather than like a broken rule.
    const offenders: string[] = [];
    for (const name of readdirSync(RULES_DIR)) {
      if (!name.endsWith(".ts")) continue;
      const src = readFileSync(join(RULES_DIR, name), "utf8");
      if (/from\s+["'](react|react-native)["']/.test(src)) offenders.push(name);
    }
    assert.deepEqual(offenders, [], `rules/ must stay pure; these import a renderer: ${offenders.join(", ")}`);
  });

  it("rules/ imports nothing from a screen or a component either", () => {
    // Same argument one level out. A rule that reaches into a screen has
    // inverted the dependency and will drag the renderer in behind it.
    const offenders: string[] = [];
    for (const name of readdirSync(RULES_DIR)) {
      if (!name.endsWith(".ts")) continue;
      const src = readFileSync(join(RULES_DIR, name), "utf8");
      if (/from\s+["'][^"']*(screens|components|state)\//.test(src)) offenders.push(name);
    }
    assert.deepEqual(offenders, []);
  });
});
