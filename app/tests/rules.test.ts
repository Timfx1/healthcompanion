describe("P2 — welcome back, with no count of what was missed", () => {
  const now = Date.parse("2026-03-01T12:00:00Z");

  it("a first-ever open is NOT a return", () => {
    // Greeting a brand new user with "good to see you again" is a small lie
    // told at the first moment they use the product.
    assert.equal(isReturn(null, now), false);
  });

  it("a weekend is not an absence", () => {
    assert.equal(isReturn(now - 2 * DAY, now), false);
  });

  it("the boundary is inclusive at ABSENCE_DAYS", () => {
    assert.equal(isReturn(now - ABSENCE_DAYS * DAY, now), true);
    assert.equal(isReturn(now - (ABSENCE_DAYS * DAY - 1), now), false);
  });

  it("A BACKWARDS CLOCK IS NOT A LONG ABSENCE", () => {
    // Timezone change or a manual clock set. Comparing a gap rather than a date
    // is what makes this fall out instead of needing a special case.
    assert.equal(isReturn(now + 30 * DAY, now), false);
  });

  it("the module exports no duration anywhere", () => {
    // The structural half of P2: a `daysAway` in scope is a number somebody
    // eventually renders. isReturn returns a boolean and nothing else.
    assert.equal(typeof isReturn(now - 12 * DAY, now), "boolean");
  });
});

