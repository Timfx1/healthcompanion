describe("§4.7 — the report refuses to guess", () => {
  const anchor = Date.parse("2026-02-01T00:00:00Z");
  const before = [
    checkIn("2026-01-20T09:00:00Z", 7),
    checkIn("2026-01-22T09:00:00Z", 7),
    checkIn("2026-01-24T09:00:00Z", 8),
  ];
  const after = [
    checkIn("2026-02-05T09:00:00Z", 3),
    checkIn("2026-02-07T09:00:00Z", 3),
    checkIn("2026-02-09T09:00:00Z", 2),
  ];

  it("empty is reachable on day one and is not a failure", () => {
    const m = deriveReport([], undefined);
    assert.equal(m.depth, "empty");
    assert.equal(m.change, "noAnchor");
    assert.equal(m.changeText, "");
  });

  it("sparse degrades rather than drawing a trend from two points", () => {
    const m = deriveReport([checkIn("2026-01-01T09:00:00Z", 5), checkIn("2026-01-02T09:00:00Z", 2)], undefined);
    assert.equal(m.depth, "sparse");
    // Two points that "look" like a dramatic improvement produce no claim.
    assert.equal(m.changeText, "");
  });

  it("MIN_FOR_TREND is the boundary, and it is inclusive", () => {
    const scores = Array.from({ length: MIN_FOR_TREND }, (_, i) => checkIn(`2026-01-0${i + 1}T09:00:00Z`, 5));
    assert.equal(deriveReport(scores.slice(0, MIN_FOR_TREND - 1), undefined).depth, "sparse");
    assert.equal(deriveReport(scores, undefined).depth, "first");
  });

  it("first: the data is fine, the anchor is missing", () => {
    const m = deriveReport([...before, ...after], undefined);
    assert.equal(m.depth, "first");
    assert.equal(m.change, "noAnchor");
  });

  it("insufficient: an anchor, but too little either side to be fair", () => {
    const m = deriveReport([checkIn("2026-01-20T09:00:00Z", 7), ...after], anchor);
    assert.equal(m.change, "insufficient");
    assert.equal(m.changeText, "");
  });

  it("STEADY IS A FINDING, not a failure to improve", () => {
    // The guilt-risk case. It must produce a claim rather than falling through
    // to silence, and the claim must be neutral.
    const flat = [
      checkIn("2026-01-20T09:00:00Z", 5), checkIn("2026-01-22T09:00:00Z", 5),
      checkIn("2026-02-05T09:00:00Z", 5), checkIn("2026-02-07T09:00:00Z", 5),
    ];
    const m = deriveReport(flat, anchor);
    assert.equal(m.change, "noChange");
    assert.equal(m.trend, "steady");
    assert.match(m.changeText, /steady/i);
  });

  it("FALLING PAIN IS IMPROVING — the one place a smaller number is good news", () => {
    const m = deriveReport([...before, ...after], anchor);
    assert.equal(m.change, "changes");
    assert.equal(m.trend, "improving");
    assert.match(m.changeText, /lower/);
  });

  it("rising pain is worsening, and the word carries the valence", () => {
    const m = deriveReport([...after.map((e) => checkIn(e.date, 8)), ...before.map((e) => checkIn(e.date, 2))], anchor);
    assert.equal(m.trend, "worsening");
  });

  it("the split is around the ANCHOR, not around now", () => {
    // If this used `Date.now()` the fixture would drift into one side and the
    // comparison would silently become a different claim.
    const m = deriveReport([...before, ...after], anchor);
    assert.equal(m.change, "changes");
    const shifted = deriveReport([...before, ...after], Date.parse("2026-03-01T00:00:00Z"));
    assert.equal(shifted.change, "insufficient");
  });

  it("pain scores come back newest first", () => {
    const scores = painScoresOf([...before, ...after]);
    assert.deepEqual(scores, [2, 3, 3, 8, 7, 7]);
  });
});

