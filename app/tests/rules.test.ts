describe("P9 — where the gates are, and where they are not", () => {
  it("a non-subscriber sees the gate, not a shopping list", () => {
    assert.equal(compareStateOf(0, false), "locked");
    assert.equal(compareStateOf(1, false), "locked");
    assert.equal(compareStateOf(9, false), "locked");
  });

  it("A SUBSCRIBER WITH ONE PHOTO IS NEVER UPSOLD", () => {
    // The case the whole three-state design exists for. Without `insufficient`
    // somebody who has already paid is shown an upgrade prompt for the thing
    // they bought — and the order of the checks in compareStateOf is what
    // prevents the mirror-image failure, where a non-subscriber is told to come
    // back with more photos and THEN gated on arrival.
    assert.equal(compareStateOf(1, true), "insufficient");
    assert.equal(compareStateOf(0, true), "insufficient");
  });

  it("two photos and premium is the ready state", () => {
    assert.equal(compareStateOf(2, true), "ready");
  });

  it("a free article is free regardless of entitlement", () => {
    // "Everything answering what-is-normal is free forever" — the half of §9
    // that matters at 2am. There is deliberately no fourth state for a
    // subscriber reading a free article.
    assert.equal(accessOf("free", false), "free");
    assert.equal(accessOf("free", true), "free");
  });

  it("only deep dives gate", () => {
    assert.equal(accessOf("deepDive", false), "deepDiveLocked");
    assert.equal(accessOf("deepDive", true), "deepDiveOpen");
  });
});

