// ============================================================
// THE PURE-RULE SUITE.
//
// These are the product's decisions, tested without a renderer. Until the
// `rules/` extraction, not one of them could be reached by anything except a
// running app, because every file that held them imported `react-native` on
// line one. The monetisation boundary, the report's refusal to guess, and the
// treatment of a gap were all unreachable by construction.
//
// RUN: node --test --experimental-strip-types tests/
// No jest, no babel, no transform step — Node 22 strips the types itself. That
// matters more than it sounds: a test suite that needs its own build is a test
// suite that stops running the first time the build breaks, and this repo has
// enough evidence about checks that quietly stop working.
//
// WHAT IS ASSERTED HERE, and it is not coverage for its own sake: every case
// below is a sentence from the spec or from §11, and several are cases that
// have ALREADY been shipped wrong somewhere in this repository.
// ============================================================

