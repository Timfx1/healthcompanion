describe("P2 — a gap is rest, and rest is never counted against anybody", () => {
  it("A RUN OF EMPTY DAYS IS ONE ROW, NOT ONE ROW PER DAY", () => {
    // Seven "a quiet day" rows would be an accusation repeated seven times,
    // however gently each one is worded. This is the arithmetic no contrast
    // check or token contract could ever see.
    const rows = withRestRows([checkIn("2026-01-01T09:00:00Z"), checkIn("2026-01-09T09:00:00Z")]);
    const rest = rows.filter((r) => r.kind === "rest");
    assert.equal(rest.length, 1);
    assert.equal(rest[0].kind === "rest" && rest[0].days, 7);
  });

  it("consecutive days produce no rest row", () => {
    const rows = withRestRows([checkIn("2026-01-01T09:00:00Z"), checkIn("2026-01-02T09:00:00Z")]);
    assert.equal(rows.filter((r) => r.kind === "rest").length, 0);
  });

  it("several entries on ONE day produce no rest row", () => {
    // Measured between day keys, not timestamps. Otherwise two captures an hour
    // apart get a rest row claiming zero quiet days.
    const rows = withRestRows([checkIn("2026-01-01T09:00:00Z"), checkIn("2026-01-01T21:00:00Z")]);
    assert.equal(rows.filter((r) => r.kind === "rest").length, 0);
  });

  it("unsorted input still produces correct gaps", () => {
    const rows = withRestRows([checkIn("2026-01-01T09:00:00Z"), checkIn("2026-01-09T09:00:00Z"), checkIn("2026-01-05T09:00:00Z")]);
    const rest = rows.filter((r) => r.kind === "rest").map((r) => (r.kind === "rest" ? r.days : 0));
    assert.deepEqual(rest, [3, 3]);
  });

  it("the copy is descriptive and never evaluative", () => {
    assert.equal(restLabel(1), "A quiet day");
    assert.equal(restLabel(12), "12 quiet days");
    for (const n of [1, 3, 7, 30, 200]) {
      const label = restLabel(n);
      // No threshold at which this becomes a warning, and no debt vocabulary.
      assert.doesNotMatch(label, /miss|behind|catch|should|lapsed|broke/i);
    }
  });
});

