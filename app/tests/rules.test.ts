describe("P1 — silent tagging that never blocks a save", () => {
  it("the normal capture has no tags, and that is not a deficiency", () => {
    assert.deepEqual(detectTags("took the long way round the block today"), []);
  });

  it("matches whole words only", () => {
    // Substring matching was the first attempt and it tagged half of
    // everything: "restless" became `rest`, "medical" became `meds`.
    assert.deepEqual(detectTags("restless and medical"), []);
    assert.deepEqual(detectTags("could not rest"), ["sleep"]);
  });

  it("returns a stable order regardless of the order words appear", () => {
    // A tag row that reshuffled between renders would be noise pretending to
    // be information.
    assert.deepEqual(detectTags("dose then pain"), ["pain", "meds"]);
    assert.deepEqual(detectTags("pain then dose"), ["pain", "meds"]);
  });

  it("is total — no input produces a throw", () => {
    for (const input of ["", "   ", "!!!", "PAIN", "pain,", "pain."]) {
      assert.doesNotThrow(() => detectTags(input));
    }
    assert.deepEqual(detectTags("PAIN"), ["pain"]);
  });
});

