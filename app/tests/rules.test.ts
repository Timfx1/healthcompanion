describe("P5 / N5 — the corridor is a range and never a deadline", () => {
  it("every phase spans days rather than naming one", () => {
    for (const corridor of CORRIDORS) {
      for (const phase of corridor.phases) {
        assert.ok(phase.toDay > phase.fromDay, `${corridor.condition}: ${phase.label} is not a range`);
      }
    }
  });

  it("EVERY PHASE CARRIES A SOURCE — a compliance requirement, not a style", () => {
    for (const corridor of CORRIDORS) {
      for (const phase of corridor.phases) {
        assert.ok(phase.sourceNote.trim().length > 0, `${corridor.condition}: ${phase.label} has no source`);
      }
    }
  });

  it("every corridor is flagged for clinical review while it is placeholder", () => {
    for (const corridor of CORRIDORS) {
      assert.equal(corridor.needsClinicalReview, true, `${corridor.condition} is not flagged`);
    }
  });

  it("no phase label implies a deadline or a failure to meet one", () => {
    for (const corridor of CORRIDORS) {
      for (const phase of corridor.phases) {
        assert.doesNotMatch(phase.label, /should|must|target|deadline|by now|expected to|behind|on track/i);
      }
    }
  });

  it("PAST THE LAST PHASE THE CORRIDOR STOPS rather than pinning the final one", () => {
    // Clamping would leave somebody on day 400 looking at the final phase
    // indefinitely, which turns a range into an overdue notice.
    const corridor = corridorFor("Ankle ligament injury (sprain)");
    assert.ok(corridor);
    assert.equal(phaseForDay(corridor!, 400), undefined);
    assert.ok(phaseForDay(corridor!, 1));
  });

  it("an unknown condition simply has no corridor", () => {
    assert.equal(corridorFor("something we do not cover"), undefined);
  });
});

