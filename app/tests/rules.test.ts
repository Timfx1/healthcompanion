describe("P4 — the sentence above the chart, including its refusal", () => {
  it("declines to claim a trend from too little", () => {
    const claim = painTrend([3], [7, 7]);
    assert.equal(claim.trend, "steady");
    assert.match(claim.text, /not enough/i);
  });

  it("the refusal does not blame the user for not logging", () => {
    const claim = painTrend([], []);
    assert.doesNotMatch(claim.text, /should|need to|must|try to|missed/i);
  });

  it("lower pain reads as improving", () => {
    assert.equal(painTrend([2, 3], [7, 8]).trend, "improving");
  });

  it("higher pain reads as worsening", () => {
    assert.equal(painTrend([7, 8], [2, 3]).trend, "worsening");
  });

  it("a difference under the meaningful delta is steady, not a micro-trend", () => {
    assert.equal(painTrend([5, 5], [5.2, 5.1]).trend, "steady");
  });
});

