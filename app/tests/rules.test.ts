/** Plain string paths: `new URL()` is a DOM type here and does not satisfy fs's PathLike. */
const RULES_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "rules");
import { describe, it } from "node:test";

import { compareStateOf, accessOf, journalStateOf } from "../src/rules/access.ts";
import { isReturn, ABSENCE_DAYS } from "../src/rules/absence.ts";
import { deriveReport, painScoresOf, MIN_FOR_TREND } from "../src/rules/report.ts";
import { withRestRows, restLabel } from "../src/rules/timeline.ts";
