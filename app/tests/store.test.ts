describe("P7 — the weekly reply", () => {
  const list: WeeklyReflection[] = [
    { weekStart: "2026-02-01", comparison: [], noticedDetail: "d", encouragement: "e" },
  ];

  it("saves the reply", () => {
    assert.equal(withReflectionReply(list, "2026-02-01", " Good week. ")[0].reply, "Good week.");
  });

  it("REPLACES an existing reply rather than appending", () => {
    const once = withReflectionReply(list, "2026-02-01", "first");
    assert.equal(withReflectionReply(once, "2026-02-01", "second")[0].reply, "second");
  });

  it("an empty reply is a no-op and returns the same array", () => {
    assert.equal(withReflectionReply(list, "2026-02-01", ""), list);
  });
});

